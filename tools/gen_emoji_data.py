#!/usr/bin/env python3
"""Generate src/emoji_data.rs for Emoxidize from public Unicode data.

Sources (downloaded to this directory on demand):
  - https://www.unicode.org/Public/emoji/latest/emoji-test.txt
  - https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-annotations-full/annotations/en/annotations.json

Usage: python3 tools/gen_emoji_data.py [output-path]
       (default output: src/emoji_data.rs next to this checkout)

Clean-room note: produced exclusively from public Unicode data files.
"""
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

TEST_URL = "https://www.unicode.org/Public/emoji/latest/emoji-test.txt"
ANN_URL = ("https://raw.githubusercontent.com/unicode-org/cldr-json/main/"
           "cldr-json/cldr-annotations-full/annotations/en/annotations.json")

HERE = Path(__file__).parent
TEST = HERE / "emoji-test.txt"
ANN = HERE / "annotations-en.json"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "src" / "emoji_data.rs"


def fetch(url: str, dest: Path) -> None:
    if dest.exists():
        return
    print(f"downloading {url}")
    try:
        urllib.request.urlretrieve(url, dest)
    except OSError:
        subprocess.run(["curl", "-fsSL", "-o", str(dest), url], check=True)


fetch(TEST_URL, TEST)
fetch(ANN_URL, ANN)

TONES = ["1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"]

CATS = {
    "Smileys & Emotion": 1,
    "People & Body": 2,
    "Animals & Nature": 3,
    "Food & Drink": 4,
    "Travel & Places": 5,
    "Activities": 6,
    "Objects": 7,
    "Symbols": 8,
    "Flags": 9,
}

def key_of(codes):
    """Normalized base key: drop skin-tone modifiers and VS16."""
    return " ".join(c for c in codes if c not in TONES and c != "FE0F")

group = None
subgroup = None
entries = []          # (codes, glyph, name, cat)
variants = {}         # key -> {tone_idx: (glyph, all_same)}
line_re = re.compile(r"^(.+?)\s*;\s*(\S+)\s*#\s*(\S+)\s+E\d+\.\d+\s+(.*)$")

for raw in TEST.read_text(encoding="utf-8").splitlines():
    line = raw.strip()
    if line.startswith("# group: "):
        group = line[len("# group: "):]
        continue
    if line.startswith("# subgroup: "):
        subgroup = line[len("# subgroup: "):]
        continue
    m = line_re.match(line)
    if not m or group not in CATS:
        continue
    if m.group(2) != "fully-qualified":
        continue
    if group == "Flags" and subgroup == "subdivision-flag":
        continue
    codes = m.group(1).split()
    glyph = m.group(3)
    name = m.group(4).strip().lower()
    tones_here = [c for c in codes if c in TONES]
    if tones_here:
        idx = TONES.index(tones_here[0])
        same = len(set(tones_here)) == 1 and tones_here[0] == TONES[idx]
        slot = variants.setdefault(key_of(codes), {})
        # prefer fully-matching-tone sequences over mixed-tone ones
        if idx not in slot or (same and not slot[idx][1]):
            slot[idx] = (glyph, same)
    else:
        entries.append((codes, glyph, name, CATS[group]))

ann = json.loads(ANN.read_text(encoding="utf-8"))["annotations"]["annotations"]

out = []
out.append("// Generated by tools/gen_emoji_data.py from public Unicode data:")
out.append("// unicode.org emoji-test.txt + CLDR annotations (en). Do not edit by hand.")
out.append("")
out.append("#[derive(Clone, Copy)]")
out.append("pub struct Emoji {")
out.append("    pub ch: &'static str,")
out.append("    pub name: &'static str,")
out.append("    pub keywords: &'static str,")
out.append("    pub cat: u8,")
out.append("}")
out.append("")
out.append("pub static EMOJIS: &[Emoji] = &[")

def as_lower_str(v):
    if isinstance(v, list):
        return " ".join(x.lower() for x in v if x)
    return (v or "").lower()

matched = 0
for codes, glyph, fallback_name, cat in entries:
    a = ann.get(glyph)
    if a:
        name = as_lower_str(a.get("tts")) or fallback_name
        kws = a.get("default") or []
        matched += 1
    else:
        name = fallback_name
        kws = []
    kws = [k for k in kws if k and k.lower() != name]
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    out.append(
        '    Emoji { ch: "%s", name: "%s", keywords: "%s", cat: %d },'
        % (glyph, esc(name), esc(" ".join(kws)), cat)
    )
out.append("];")
out.append("")
out.append("/// Base glyph -> the five skin-tone variants (light..dark), from emoji-test.txt.")
out.append("pub static TONE_VARIANTS: &[(&str, [&str; 5])] = &[")

canon_keys = {key_of(c) for c, _, _, _ in entries}
for key in sorted(variants):
    if key not in canon_keys:
        continue
    slot = variants[key]
    vals = [slot.get(i, (None, False))[0] for i in range(5)]
    if any(v is None for v in vals):
        print("WARN: incomplete tones for key %r: %r" % (key, vals), file=sys.stderr)
        continue
    base_glyph = next((g for c, g, _, _ in entries if key_of(c) == key), None)
    out.append('    ("%s", ["%s"]),'
               % (base_glyph, '","'.join(vals)))
out.append("];")
out.append("")

OUT.write_text("\n".join(out), encoding="utf-8")

per_cat = {}
for _, _, _, cat in entries:
    per_cat[cat] = per_cat.get(cat, 0) + 1
print("canonical entries: %d (annotations matched: %d)" % (len(entries), matched))
print("tone-variant bases: %d" % len(canon_keys & set(variants)))
for cat in sorted(per_cat):
    print("  cat %d: %d" % (cat, per_cat[cat]))
